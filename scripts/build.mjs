import { build } from 'esbuild';
import { gzipSync } from 'node:zlib';
import { writeFileSync, mkdirSync, rmSync, readFileSync, readdirSync, statSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const p = (s) => root + s;

// 1) The decoding worker (engine + ZXing WASM) as one self-contained script. It is inlined as a
//    string and started from a blob: URL → zero asset configuration in every bundler.
const w = await build({
  entryPoints: [p('src/worker.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  // WASM is gzip-compressed before base64: ~45 % smaller string, ~20 % less to download
  define: { __ZXING_WASM_GZ_B64__: JSON.stringify(gzipSync(readFileSync(p('node_modules/zxing-wasm/dist/reader/zxing_reader.wasm')), { level: 9 }).toString('base64')) },
});
const workerJs = w.outputFiles[0].text;
writeFileSync(
  p('src/worker-source.generated.ts'),
  `// AUTO-GENERATED by scripts/build.mjs – do not edit\n// typed as string so the emitted .d.ts stays tiny\nconst source: string = ${JSON.stringify(workerJs)};\nexport default source;\n`,
);
if (process.argv.includes('--worker-only')) process.exit(0);

// 2) library bundles
rmSync(p('dist'), { recursive: true, force: true });
mkdirSync(p('dist'), { recursive: true });
const common = { bundle: true, minify: true, sourcemap: true, sourcesContent: false, target: 'es2020', platform: 'browser', external: ['react', 'vue'] };
const ENGINE = /worker-source\.generated$/;
const JSQR = /decoder-jsqr$/; // main-thread fallback, only needed when workers/WASM are blocked
const entries = { index: p('src/index.ts'), react: p('src/react.ts'), vue: p('src/vue.ts'), svelte: p('src/svelte.ts'), sr: p('src/sr-entry.ts') };

// ESM: code-split → the engine is its own chunk, fetched only when a scanner starts
await build({
  ...common, entryPoints: entries, format: 'esm', splitting: true, outdir: p('dist'),
  entryNames: '[name]', chunkNames: 'chunks/[name]-[hash]',
});
// Next.js App Router: the React wrapper is a client component
{
  const f = p('dist/react.js');
  writeFileSync(f, "'use client';\n" + readFileSync(f, 'utf8'));
}

// CJS: wrappers re-use index.cjs, and index.cjs loads the engine from one shared file on demand
const shareIndex = { name: 'share-index', setup(b) { b.onResolve({ filter: /^\.\/(element|scanner)$/ }, () => ({ path: 'kqrcode', external: true })); } };
const cjsEngine = { name: 'cjs-engine', setup(b) {
  b.onResolve({ filter: ENGINE }, () => ({ path: './engine.cjs', external: true }));
  b.onResolve({ filter: JSQR }, () => ({ path: './jsqr.cjs', external: true }));
} };
await build({ ...common, entryPoints: [p('src/decoder-jsqr.ts')], format: 'cjs', outfile: p('dist/jsqr.cjs') });
writeFileSync(p('dist/engine.cjs'), `"use strict";Object.defineProperty(exports,"__esModule",{value:true});exports.default=${JSON.stringify(workerJs)};\n`);
for (const [name, entry] of Object.entries(entries)) {
  const banner = name === 'react' ? { js: "'use client';" } : undefined;
  const plugins = ['react', 'vue', 'svelte'].includes(name) ? [shareIndex] : [cjsEngine];
  await build({ ...common, banner, plugins, entryPoints: [entry], format: 'cjs', outfile: p(`dist/${name}.cjs`) });
}

// CLI (npx kqrcode …) – Node, no dependencies
{
  const version = JSON.parse(readFileSync(p('package.json'), 'utf8')).version;
  await build({
    entryPoints: [p('src/cli.ts')], bundle: true, minify: false, platform: 'node', target: 'node18', format: 'esm',
    banner: { js: '#!/usr/bin/env node' }, define: { __VERSION__: JSON.stringify(version) }, outfile: p('dist/cli.js'),
  });
}

// 3) <script> build (CDN / plain HTML): window.KQRCode. Small; the engine is fetched on first use
//    from kqrcode.engine.js next to it (same directory on jsDelivr / unpkg / your server).
const remoteEngine = {
  name: 'remote-engine',
  setup(b) {
    b.onResolve({ filter: ENGINE }, () => ({ path: 'engine', namespace: 'kqr-remote' }));
    b.onResolve({ filter: JSQR }, () => ({ path: 'jsqr', namespace: 'kqr-remote' }));
    b.onLoad({ filter: /^jsqr$/, namespace: 'kqr-remote' }, () => ({
      loader: 'js',
      // classic scripts may use dynamic import(); the fallback is an ES module next to this file
      contents: `export const jsqrDecoder = { slow: true, decode: (img, inv) => import(new URL('kqrcode.jsqr.js', (typeof __KQR_BASE__ !== 'undefined' && __KQR_BASE__) || location.href).href).then((m) => m.jsqrDecoder.decode(img, inv)) };`,
    }));
    b.onLoad({ filter: /^engine$/, namespace: 'kqr-remote' }, () => ({
      loader: 'js',
      contents: `export default fetch(new URL('kqrcode.engine.js', (typeof __KQR_BASE__ !== 'undefined' && __KQR_BASE__) || location.href))
        .then((r) => { if (!r.ok) throw new Error('kqrcode: cannot load kqrcode.engine.js (' + r.status + ')'); return r.text(); });`,
    }));
  },
};
await build({
  ...common, plugins: [remoteEngine], entryPoints: [p('src/index.ts')], format: 'iife', globalName: 'KQRCode',
  // remember where this script was loaded from (document.currentScript is only set while it runs)
  banner: { js: 'var __KQR_BASE__=typeof document!=="undefined"&&document.currentScript?document.currentScript.src:void 0;' },
  outfile: p('dist/kqrcode.global.js'),
});
writeFileSync(p('dist/kqrcode.engine.js'), workerJs);
await build({ ...common, entryPoints: [p('src/decoder-jsqr.ts')], format: 'esm', outfile: p('dist/kqrcode.jsqr.js') });

// 4) React Native: the scanner runs in a react-native-webview. The page script is fully
//    self-contained (engine + jsQR fallback inlined) so apps work offline and need no assets.
{
  const rt = await build({
    ...common, sourcemap: false, entryPoints: [p('src/index.ts')], format: 'iife', globalName: 'KQRCode', write: false,
  });
  writeFileSync(
    p('src/rn-runtime.generated.ts'),
    `// AUTO-GENERATED by scripts/build.mjs – do not edit\nconst runtime: string = ${JSON.stringify(rt.outputFiles[0].text)};\nexport default runtime;\n`,
  );
  // Metro only resolves .js by default (not .cjs/.mjs everywhere), so the React Native entry is
  // CommonJS in plain .js files, in a folder marked "type": "commonjs" for Node.
  mkdirSync(p('dist/rn'), { recursive: true });
  writeFileSync(p('dist/rn/package.json'), '{ "type": "commonjs" }\n');
  writeFileSync(p('dist/rn/runtime.js'), `module.exports=${JSON.stringify(rt.outputFiles[0].text)};\n`);
  const sharedRuntime = { name: 'rn-runtime', setup(b) { b.onResolve({ filter: /rn-runtime\.generated$/ }, () => ({ path: './runtime.js', external: true })); } };
  await build({
    ...common, plugins: [sharedRuntime], entryPoints: [p('src/react-native.ts')], format: 'cjs', outfile: p('dist/rn/index.js'),
    external: ['react', 'react-native', 'react-native-webview'],
  });
}

// size report
const gz = (f) => gzipSync(readFileSync(f), { level: 9 }).length;
const kb = (n) => (n / 1024).toFixed(1).padStart(7) + ' kB';
const list = [...readdirSync(p('dist')).map((f) => 'dist/' + f), ...readdirSync(p('dist/chunks')).map((f) => 'dist/chunks/' + f), ...readdirSync(p('dist/rn')).map((f) => 'dist/rn/' + f)]
  .filter((f) => /\.(js|cjs)$/.test(f));
console.log('file'.padEnd(52), '     raw', '    gzip');
for (const f of list) console.log(f.padEnd(52), kb(statSync(p(f)).size), kb(gz(p(f))));
console.log('built');
